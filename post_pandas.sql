----Aggregate Function----
SELECT sum(a.salary) as salary,avg(a.salary)::numeric(10,2) as average_salary,b.department_name
FROM employees a
join departmants b on a.department_id = b.department_id
GROUP BY b.department_name

SELECT max(a.salary) as maximum_salary,min(a.salary) as minimum_salary,b.department_name
FROM employees a
join departmants b on a.department_id = b.department_id
