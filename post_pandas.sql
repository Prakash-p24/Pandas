create table departmants(
    department_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	department_name varchar(255),
	location varchar(255)
)


create table employees(
    employee_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	first_name varchar(255),
	last_name varchar(255),
	salary decimal(10,2),
	hire_date date,
	department_id int,CONSTRAINT fk_employees
        FOREIGN KEY (department_id)
        REFERENCES departmants (department_id)
        ON DELETE SET NULL
        ON UPDATE CASCADE
)


